/**
 * Resumable multipart uploads for the ShardDO's paging (docs/PROTOCOL.md §9.1 "Paging").
 *
 * A file is produced as a sequence of items (batch headers and rows, index entries, batch entries). PartSink cuts
 * that sequence into parts of exactly `partSize` bytes (the last one shorter), uploads each part as soon as it is
 * full and hands the caller what to persist with it: the part's etag and SHA-256, and the position to resume from
 * (the item under the cut and how many of its bytes already sit in earlier parts). A slice of work ends after a
 * number of parts; whatever the buffer holds then is regenerated by the next slice from the persisted position, so a
 * restart repeats at most one part. Items are opaque here: the generators live in the ShardDO.
 */
import { sha256 } from "./http";

/** Where a file's production resumes: the item `pos` names, of which `skip` bytes are already in uploaded parts. */
export interface Resume<P> {
  pos: P;
  skip: number;
}

/** One uploaded part, as the caller persists it. */
export interface PartDone<P> {
  etag: string;
  sha: Uint8Array;
  bytes: number;
  resume: Resume<P> | null;
}

export class PartSink<P> {
  private readonly buf: Uint8Array;
  private fill = 0;
  private cur: { pos: P; written: number } | null = null;
  /** Parts this sink uploaded (the slice's budget counts these). */
  uploaded = 0;

  /**
   * `partsBefore` parts (all full) were uploaded by earlier slices. `upload` sends one part and returns its etag;
   * `committed` runs after each upload and persists the progress (parts, hash, resume position) in one transaction.
   */
  constructor(
    private readonly partSize: number,
    private readonly partsBefore: number,
    private readonly upload: (partNumber: number, bytes: Uint8Array) => Promise<string>,
    private readonly committed: (p: PartDone<P>) => void,
  ) {
    if (!Number.isInteger(partSize) || partSize < 1) throw new RangeError("PartSink: bad part size");
    this.buf = new Uint8Array(partSize);
  }

  /** The file offset at which the next byte goes. */
  get offset(): number {
    return (this.partsBefore + this.uploaded) * this.partSize + this.fill;
  }

  /** Appends `item` (from its byte `skip` on, when resuming inside it), uploading every part that fills. */
  async write(pos: P, item: Uint8Array, skip = 0): Promise<void> {
    this.cur = { pos, written: skip };
    let o = skip;
    while (o < item.length) {
      const k = Math.min(item.length - o, this.partSize - this.fill);
      this.buf.set(item.subarray(o, o + k), this.fill);
      this.fill += k;
      o += k;
      this.cur.written = o;
      if (this.fill === this.partSize) await this.flush();
    }
  }

  /** Uploads what the buffer holds: a full part, or the file's last one when the sequence has ended. */
  async flush(): Promise<void> {
    if (this.fill === 0) return;
    const bytes = this.buf.subarray(0, this.fill);
    const sha = await sha256(bytes);
    const etag = await this.upload(this.partsBefore + this.uploaded + 1, bytes);
    const n = bytes.length;
    this.uploaded++;
    this.fill = 0;
    this.committed({ etag, sha, bytes: n, resume: this.cur ? { pos: this.cur.pos, skip: this.cur.written } : null });
  }
}
